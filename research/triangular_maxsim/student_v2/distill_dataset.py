"""Build the TRACE v2 biaffine-student distillation dataset.

Orchestrator that combines five source streams into a single
deterministic JSONL corpus:

1. **Synthetic enterprise lane** (primary generalization driver;
   ``rag.prose.enterprise``). Six training industries + two held-out
   OOD industries, 3 shapes x 3 adversarials x 3 paraphrases.
   Generated by :mod:`synthetic.enterprise_generator`.
2. **Veracier curated variants** (capped guardrail, **3x upweight
   only**). Used as gold-labelled sanity signal on enterprise prose;
   **not** the generalization lever (see plan section
   "Explicit anti-overfit rule on Veracier").
3. **External benchmarks** - HaluEval QA/Summ and RAGTruth QA/Summ
   rows from the proof-bundle-v1 external bench dump. Carries both
   gold labels and v1 teacher outputs.
4. **Audit log** (optional) - per-call teacher scores from live
   TRACE production traffic. Unlabeled distillation signal only,
   capped to 10k rows to avoid swamping the curated sources.
5. **(Future)** - secondary synthetic lanes (structured / code_rag /
   agentic_trace). These follow the same recipe; stubs are wired in
   but the generators are deferred to the next PR.

Each row carries the three-axis supervision labels required by the
v2 five-head student:

```python
{
  "pair_id":        "...",
  "class_key":      "rag.prose.enterprise" | "rag.prose.short_factoid" | ...,
  "response_text":  "...",
  "evidence_text":  "...",
  "gold_band":      "green" | "amber" | "red" | null,
  "phi_hints":      {"exact_overlap": 0.41, "numeric_overlap": 1.0, ...},
  # Three-axis labels (teacher-derived, filled by a later scoring pass):
  "turn_score":             0.74,   # hallucination (response-side)
  "turn_band":              "amber",
  "token_support_labels":   null,   # filled by teacher
  "dead_weight_unit_labels": null,   # filled by teacher
  "coverage_unit_labels":    null,   # filled by teacher
  # Provenance:
  "source":          "synthetic_enterprise" | "veracier" | "halueval_qa" | ...,
  "split_hint":      "train" | "ood_eval",
  "upweight_factor": 1 | 2 | 3,
  "synthetic":       bool,
  "role":            "grounded" | "entity_swap" | ... (synthetic only),
  "industry":        "finance" | ... (synthetic enterprise only),
  "notes":           str (free-text),
}
```

The writer emits split JSONL files (train / val / test / ood_eval) in
``--out`` and a ``manifest.json`` with source counts, SHA-256 hashes,
and the exact generator parameters used so the dataset is fully
reproducible.

Teacher-scoring the synthetic lane and filling in
``token_support_labels`` / ``dead_weight_unit_labels`` /
``coverage_unit_labels`` is performed by a separate script
(``score_rows_with_teacher.py``; scaffolded separately) - this file
emits the **pre-teacher** corpus so the pipeline stays hermetic and
unit-testable without requiring a live RunPod endpoint.
"""

