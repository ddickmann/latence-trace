def _base_row(
    *,
    pair_id: str,
    class_key: str,
    response_text: str,
    evidence_text: str,
    gold_band: str | None,
    source: str,
    split_hint: str,
    upweight_factor: int,
    synthetic: bool,
    role: str | None = None,
    industry: str | None = None,
    sub_domain: str | None = None,
    shape: str | None = None,
    notes: str = "",
    turn_band: str | None = None,
    turn_score: float | None = None,
) -> dict[str, Any]:
    return {
        "pair_id": pair_id,
        "class_key": class_key,
        "response_text": response_text,
        "evidence_text": evidence_text,
        "gold_band": gold_band,
        "turn_band": turn_band,
        "turn_score": turn_score,
        # Three-axis placeholders; populated by the teacher-scoring pass.
        "token_support_labels": None,
        "dead_weight_unit_labels": None,
        "coverage_unit_labels": None,
        # Provenance.
        "source": source,
        "split_hint": split_hint,
        "upweight_factor": upweight_factor,
        "synthetic": synthetic,
        "role": role,
        "industry": industry,
        "sub_domain": sub_domain,
        "shape": shape,
        "notes": notes,
        "phi_hints": _phi_hints(response_text, evidence_text),
    }


