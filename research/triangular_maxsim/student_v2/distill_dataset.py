def _sha256_of_file(path: pathlib.Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def _write_jsonl(path: pathlib.Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w") as fh:
        for row in rows:
            fh.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")


def build_manifest(
    out_dir: pathlib.Path,
    splits: dict[str, list[dict]],
    *,
    synthetic_stats: SyntheticStats,
    master_seed: int,
    passages_per_bucket: int,
    min_jaccard: float,
    veracier_upweight: int,
    audit_log_path: pathlib.Path | None,
    audit_log_cap: int,
) -> dict[str, Any]:
    """Emit the reproducibility manifest as a plain dict."""
    per_split: dict[str, Any] = {}
    per_source: Counter[str] = Counter()
    per_class_key: Counter[str] = Counter()
    per_role: Counter[str] = Counter()
    for split_name, rows in splits.items():
        split_path = out_dir / f"{split_name}.jsonl"
        try:
            path_field = str(split_path.relative_to(ROOT))
        except ValueError:
            path_field = str(split_path)
        per_split[split_name] = {
            "rows": len(rows),
            "path": path_field,
            "sha256": _sha256_of_file(split_path) if split_path.exists() else None,
        }
        for r in rows:
            per_source[r.get("source", "unknown")] += 1
            per_class_key[r.get("class_key", "unknown")] += 1
            per_role[str(r.get("role") or "non_synthetic")] += 1

    return {
        "generated_by": "research/triangular_maxsim/student_v2/distill_dataset.py",
        "plan": "v2_biaffine_student_c9f07f3d.plan.md",
        "generator_params": {
            "master_seed": master_seed,
            "passages_per_bucket": passages_per_bucket,
            "min_jaccard_synthetic": min_jaccard,
            "veracier_upweight": veracier_upweight,
            "audit_log_cap": audit_log_cap,
            "audit_log_path": (
                str(audit_log_path) if audit_log_path else None
            ),
        },
        "splits": per_split,
        "source_counts": dict(per_source),
        "class_key_counts": dict(per_class_key),
        "role_counts": dict(per_role),
        "synthetic_enterprise_stats": dataclasses.asdict(synthetic_stats),
    }


# ---------------------------------------------------------------------------
# Main entry point
# ---------------------------------------------------------------------------


def collect_rows(
    *,
    audit_log: pathlib.Path | None,
    passages_per_bucket: int,
    master_seed: int,
    emit_ood: bool,
    min_jaccard: float,
    audit_log_cap: int,
) -> tuple[list[dict], SyntheticStats]:
    stats = SyntheticStats()
    rows: list[dict] = []

    rows.extend(
        iter_synthetic_enterprise(
            passages_per_bucket=passages_per_bucket,
            master_seed=master_seed,
            emit_ood=emit_ood,
            min_jaccard=min_jaccard,
            stats=stats,
        )
    )
    rows.extend(iter_veracier(PROOF_DIR / "variants.curated.jsonl"))
    for bench_file in sorted((PROOF_DIR / "external_bench").glob("*_rows.jsonl")):
        rows.extend(iter_external(bench_file))

    if audit_log:
        rows.extend(iter_audit_log(audit_log, cap=audit_log_cap))

    return rows, stats


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Build the TRACE v2 student distillation dataset."
    )
    parser.add_argument("--audit-log", type=pathlib.Path, default=None)
    parser.add_argument("--audit-log-cap", type=int, default=10_000)
    parser.add_argument(
        "--out",
        type=pathlib.Path,
        default=ROOT / "research/triangular_maxsim/student_v2/data",
    )
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--passages-per-bucket",
        type=int,
        default=60,
        help="Passages per (industry, sub_domain, shape, template) bucket.",
    )
    parser.add_argument(
        "--min-jaccard",
        type=float,
        default=MIN_JACCARD_SYNTHETIC,
        help="Minimum Jaccard between grounded + adversarial response.",
    )
    parser.add_argument(
        "--skip-ood",
        action="store_true",
        help="If set, do not emit the two held-out OOD industries.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Collect + count rows without writing files.",
    )
    args = parser.parse_args(argv)
    args.out.mkdir(parents=True, exist_ok=True)

    rows, syn_stats = collect_rows(
        audit_log=args.audit_log,
        passages_per_bucket=args.passages_per_bucket,
        master_seed=args.seed,
        emit_ood=not args.skip_ood,
        min_jaccard=args.min_jaccard,
        audit_log_cap=args.audit_log_cap,
    )
    print(f"collected rows: {len(rows)}")
    print(
        f"  synthetic_enterprise: total={syn_stats.total_generated} "
        f"kept={syn_stats.kept} dropped_jaccard={syn_stats.dropped_jaccard}"
    )

    splits = split_rows(rows, args.seed)
    for name, r in splits.items():
        print(f"  {name:10s}: {len(r):6d}")

    if args.dry_run:
        return 0

    for name, r in splits.items():
        _write_jsonl(args.out / f"{name}.jsonl", r)

    manifest = build_manifest(
        args.out,
        splits,
        synthetic_stats=syn_stats,
        master_seed=args.seed,
        passages_per_bucket=args.passages_per_bucket,
        min_jaccard=args.min_jaccard,
        veracier_upweight=VERACIER_UPWEIGHT,
        audit_log_path=args.audit_log,
        audit_log_cap=args.audit_log_cap,
    )
    manifest_path = args.out / "manifest.json"
    with manifest_path.open("w") as fh:
        json.dump(manifest, fh, indent=2, sort_keys=True)
    print(f"wrote manifest: {manifest_path}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
