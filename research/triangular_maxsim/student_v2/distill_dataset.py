# ---------------------------------------------------------------------------
# Lexical feature helpers (12-dim phi "hint" channel - cheap signals only).
# ---------------------------------------------------------------------------


_NUM = re.compile(r"[-+]?\d+(?:[.,]\d+)?")
_IDENT = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\.[A-Za-z_][A-Za-z0-9_]*")
_WORD = re.compile(r"[A-Za-z0-9_]+")
_MARKDOWN_TABLE_HINT = re.compile(r"^\s*\|.*\|.*\|", re.MULTILINE)
_CODE_FENCE_HINT = re.compile(r"```[a-zA-Z0-9_+-]*\n")


def _tokens(text: str) -> list[str]:
    return [t.lower() for t in _WORD.findall(text or "")]


def _overlap(a: list[str], b: list[str]) -> float:
    if not a or not b:
        return 0.0
    sa, sb = set(a), set(b)
    inter = len(sa & sb)
    return inter / max(len(sa), 1)


def _numeric_overlap(a: str, b: str) -> float:
    aa = set(_NUM.findall(a or ""))
    bb = set(_NUM.findall(b or ""))
    if not aa:
        return 0.0
    return len(aa & bb) / len(aa)


def _identifier_overlap(a: str, b: str) -> float:
    aa = set(_IDENT.findall(a or ""))
    bb = set(_IDENT.findall(b or ""))
    if not aa:
        return 0.0
    return len(aa & bb) / len(aa)


def _detect_source_type(text: str) -> str:
    text = text or ""
    if _CODE_FENCE_HINT.search(text) or "def " in text:
        return "code"
    if _MARKDOWN_TABLE_HINT.search(text):
        return "table"
    stripped = text.strip()
    if stripped.startswith(("##", "###", "# ")):
        return "markdown"
    if stripped.startswith("{") and stripped.endswith("}"):
        return "json"
    if "passage " in text.lower():
        return "passage_enum"
    return "prose"


def _phi_hints(response: str, evidence: str) -> dict[str, Any]:
    """Return the 4 cheap phi signals used in training.

    The full 12-dim phi tensor is computed per (response-token,
    evidence-token) pair at training time; this dict carries the
    hint-level pre-aggregated signals used for manifest auditing +
    qualitative dataset checks.
    """
    r_tok = _tokens(response)
    e_tok = _tokens(evidence)
    return {
        "exact_overlap": round(_overlap(r_tok, e_tok), 4),
        "numeric_overlap": round(_numeric_overlap(response, evidence), 4),
        "identifier_overlap": round(_identifier_overlap(response, evidence), 4),
        "source_type": _detect_source_type(evidence),
    }


