def iter_audit_log(path: pathlib.Path, *, cap: int = 10_000) -> Iterator[dict]:
    if not path.exists():
        return
    count = 0
    with path.open() as fh:
        for line in fh:
            if count >= cap:
                return
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                continue
            req = rec.get("request") or {}
            resp = rec.get("response") or {}
            response_text = req.get("response_text") or ""
            raw_context = req.get("raw_context") or ""
            if isinstance(raw_context, list):
                raw_context = "\n".join(str(x) for x in raw_context)
            band = resp.get("band") or resp.get("risk_band") or "unknown"
            if isinstance(band, dict):
                band = band.get("value", "unknown")
            class_key = (
                (rec.get("corpus_route") or {}).get("corpus_type")
                or req.get("class_key")
                or "rag.prose.enterprise"
            )
            yield _base_row(
                pair_id=rec.get("request_id") or f"audit::{count}",
                class_key=class_key,
                response_text=response_text,
                evidence_text=raw_context,
                gold_band=None,
                source="audit_log",
                split_hint="train",
                upweight_factor=1,
                synthetic=False,
                notes="live_traffic",
                turn_band=str(band).lower(),
                turn_score=resp.get("groundedness") or resp.get("groundedness_v2"),
            )
            count += 1


def iter_veracier(path: pathlib.Path) -> Iterator[dict]:
    """Veracier curated variants at 3x upweight (the plan's cap).

    Each underlying row is emitted VERACIER_UPWEIGHT times with the
    same pair_id and incrementally-suffixed row_id. Pair-aware
    splitting keeps all copies in the same split.
    """
    if not path.exists():
        return
    with path.open() as fh:
        for line in fh:
            try:
                v = json.loads(line)
            except json.JSONDecodeError:
                continue
            response_text = v.get("response_text") or v.get("answer") or ""
            raw_context = v.get("raw_context") or v.get("context") or ""
            if isinstance(raw_context, list):
                raw_context = "\n".join(str(x) for x in raw_context)
            gold = (v.get("expected_band") or v.get("label") or "").lower() or None
            case_id = v.get("case_id") or v.get("row_id") or "veracier_anon"
            for k in range(VERACIER_UPWEIGHT):
                yield _base_row(
                    pair_id=str(case_id),
                    class_key="rag.prose.enterprise",
                    response_text=response_text,
                    evidence_text=raw_context,
                    gold_band=gold,
                    source="veracier",
                    split_hint="train",
                    upweight_factor=VERACIER_UPWEIGHT,
                    synthetic=False,
                    notes=f"veracier_copy_{k + 1}_of_{VERACIER_UPWEIGHT}",
                    turn_band=gold,
                )


def iter_external(path: pathlib.Path) -> Iterator[dict]:
    if not path.exists():
        return
    with path.open() as fh:
        for line in fh:
            try:
                r = json.loads(line)
            except json.JSONDecodeError:
                continue
            response_text = r.get("response_text") or ""
            raw_context = r.get("raw_context") or ""
            if isinstance(raw_context, list):
                raw_context = "\n".join(str(x) for x in raw_context)
            band = (r.get("band") or "").lower() or None
            gold = (r.get("expected_band") or r.get("expected_label") or "").lower()
            if gold == "hallucinated":
                gold = "red"
            elif gold in {"grounded", "faithful"}:
                gold = "green"
            else:
                gold = gold or None
            row_id = r.get("row_id") or ""
            pair_id = row_id.replace("_halluc", "") or str(id(r))
            source = r.get("bench") or path.stem
            # Infer class_key from bench name, defaulting to short_factoid.
            bench_lower = str(source).lower()
            if "halueval_summ" in bench_lower:
                class_key = "rag.prose.multi_claim"
            elif "halueval_qa" in bench_lower:
                class_key = "rag.prose.short_factoid"
            elif "ragtruth_qa" in bench_lower:
                class_key = "rag.prose.short_factoid"
            elif "ragtruth_summ" in bench_lower:
                class_key = "rag.prose.multi_claim"
            elif "ragtruth_data2text" in bench_lower:
                class_key = "rag.structured"
            else:
                class_key = "rag.prose.short_factoid"
            yield _base_row(
                pair_id=pair_id,
                class_key=class_key,
                response_text=response_text,
                evidence_text=raw_context,
                gold_band=gold,
                source=str(source),
                split_hint="train",
                upweight_factor=1,
                synthetic=False,
                notes=row_id,
                turn_band=band,
                turn_score=r.get("score"),
            )


