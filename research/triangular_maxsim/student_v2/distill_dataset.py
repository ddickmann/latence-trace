# Splitter
# ---------------------------------------------------------------------------


def split_rows(
    rows: list[dict],
    seed: int,
) -> dict[str, list[dict]]:
    """Pair-aware + split-hint-aware train/val/test/ood_eval split.

    ``ood_eval`` rows are routed to the dedicated OOD split and never
    placed in train/val/test. Rows sharing a ``pair_group`` (or
    ``pair_id`` if no group is set) are kept in the same split so the
    ranking loss does not leak. Non-OOD rows are split 80 / 10 / 10.
    """
    rng = random.Random(seed)
    ood: list[dict] = []
    in_dist: list[dict] = []
    for r in rows:
        if r.get("split_hint") == "ood_eval":
            ood.append(r)
        else:
            in_dist.append(r)

    buckets: dict[str, list[dict]] = defaultdict(list)
    for r in in_dist:
        key = r.get("pair_group") or r.get("pair_id") or f"_solo_{id(r)}"
        buckets[key].append(r)

    keys = sorted(buckets)
    rng.shuffle(keys)
    n_val = max(1, int(0.10 * len(keys)))
    n_test = max(1, int(0.10 * len(keys)))
    val_k = set(keys[:n_val])
    test_k = set(keys[n_val : n_val + n_test])

    splits: dict[str, list[dict]] = {
        "train": [],
        "val": [],
        "test": [],
        "ood_eval": ood,
    }
    for k in keys:
        dest = (
            "val" if k in val_k
            else ("test" if k in test_k else "train")
        )
        splits[dest].extend(buckets[k])
    return splits


