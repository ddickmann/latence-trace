# Synthetic-lane adapter: SyntheticRow -> dict with three-axis placeholders.
# ---------------------------------------------------------------------------


@dataclasses.dataclass
class SyntheticStats:
    total_generated: int = 0
    kept: int = 0
    dropped_jaccard: int = 0


def iter_synthetic_enterprise(
    *,
    passages_per_bucket: int,
    master_seed: int,
    emit_ood: bool,
    min_jaccard: float,
    stats: SyntheticStats,
) -> Iterator[dict]:
    """Emit synthetic enterprise rows with per-pair Jaccard gating.

    Grounded rows always pass. Adversarial rows are gated against
    their grounded counterpart's v0 paraphrase - if the Jaccard score
    falls below ``min_jaccard`` the entire ``(pair_id, role)`` bucket
    is dropped (all 3 paraphrases).
    """
    # First pass: materialise rows so we can compute per-pair Jaccard.
    rows: list[SyntheticRow] = list(
        generate_enterprise_rows(
            passages_per_bucket=passages_per_bucket,
            master_seed=master_seed,
            emit_ood=emit_ood,
        )
    )
    stats.total_generated = len(rows)

    grounded_v0: dict[str, str] = {}
    for r in rows:
        if r.role == "grounded" and r.paraphrase_variant == "v0":
            grounded_v0[r.pair_id] = r.response_text

    dropped_pairs: set[tuple[str, str]] = set()
    for r in rows:
        if r.role == "grounded":
            continue
        g = grounded_v0.get(r.pair_id)
        if g is None:
            continue
        # Check v0 once per (pair, role); drop the entire role bucket.
        if r.paraphrase_variant != "v0":
            continue
        if not jaccard_gate(g, r.response_text, min_jaccard=min_jaccard).kept:
            dropped_pairs.add((r.pair_id, r.role))
    stats.dropped_jaccard = len(dropped_pairs)

    for r in rows:
        if (r.pair_id, r.role) in dropped_pairs:
            continue
        row = _base_row(
            pair_id=f"{r.pair_id}::{r.role}::{r.paraphrase_variant}",
            class_key=r.class_key,
            response_text=r.response_text,
            evidence_text=r.evidence_text,
            gold_band=(
                "green" if r.intended_label == "grounded" else "red"
            ),
            source="synthetic_enterprise",
            split_hint=r.split_hint,
            upweight_factor=1,
            synthetic=True,
            role=r.role,
            industry=r.industry,
            sub_domain=r.sub_domain,
            shape=r.shape,
            notes=r.notes,
        )
        row["synthetic_template_id"] = r.template_id
        row["synthetic_modified_slots"] = list(r.modified_slots)
        row["synthetic_dropped_sentences"] = list(r.dropped_sentences)
        row["synthetic_paraphrase_variant"] = r.paraphrase_variant
        # Keep the pair_id at the source level so pair-aware split keeps all
        # paraphrases of the same (passage, role) together.
        row["pair_group"] = r.pair_id
        stats.kept += 1
        yield row


